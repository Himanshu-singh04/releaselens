    def test_multiple_assertions_aggregation_preserves_unknowns_and_order(self):
        for statuses, aggregate in [(('pass', 'pass'), 'pass'), (('pass', 'unknown'), 'unknown'),
                                     (('fail', 'unknown'), 'fail'), (('unknown', 'unknown'), 'unknown')]:
            bundle = value_bundle('actual', 'actual')
