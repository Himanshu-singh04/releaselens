def canonical(value):
    """Independent restricted JCS for B3 tests, not an extension of B2's recipe.

    UTF-16 sorted keys; strings, safe integers, bool/null, and exactly float1.5.
    Those primitives have the same spelling in compact stdlib JSON and JCS.
    Other floats are deliberately unsupported, not silently rounded by an oracle.
    """
    def ordered(v):
        if type(v) is dict:
            return {k: ordered(v[k]) for k in sorted(v, key=lambda k: k.encode('utf-16-be'))}
        if type(v) is list:
            return [ordered(x) for x in v]
        assert type(v) in (str, int, bool, type(None)) or (type(v) is float and v == 1.5)
        if type(v) is int:
            assert abs(v) <= 2**53 - 1
        return v
    return json.dumps(ordered(value), ensure_ascii=False, separators=(',', ':')).encode()


def digest(raw):
    return 'sha256:' + hashlib.sha256(raw).hexdigest()


def H(value):
    return digest(canonical(value))


def without(value, field):
    return {k: v for k, v in value.items() if k != field}


def seal(bundle):
    """Independent dependency-order resealing, before Contract import/evaluation."""
    suite = bundle['suite_snapshot']
    for artifact in [*suite['artifacts'], *bundle['artifacts']]:
        artifact['sha256'] = digest(artifact['content'].encode()) if artifact['media_type'] == 'text/plain' else H(artifact['content'])
    artifacts = {a['artifact_id']: a for a in suite['artifacts']}
    for case in suite['cases']:
        ids = {r['artifact_id'] for r in [case['input'], *case['policy_refs']]}
        case['case_hash'] = H({'definition': without(case, 'case_hash'),
                               'artifacts': [artifacts[k] for k in sorted(ids)]})
    suite['suite_hash'] = H(without(suite, 'suite_hash'))
    cases = {case['case_id']: case for case in suite['cases']}
    for run in bundle['runs']:
        run['case_hash'] = cases[run['case_id']]['case_hash']
    bundle['bundle_hash'] = H(without(bundle, 'bundle_hash'))
    return bundle


def fixture(owner='baseline'):
    return json.loads((ROOT / 'fixtures/b2' / (owner + '.json')).read_bytes())


def effect_bundle():
    bundle = fixture()
    bundle['suite_snapshot']['cases'] = bundle['suite_snapshot']['cases'][:1]
    bundle['runs'] = bundle['runs'][:1]
    bundle['artifacts'] = [a for a in bundle['artifacts'] if a['artifact_id'].endswith('C01')]
    return bundle


def parts(bundle):
    run = bundle['runs'][0]
    assertion = bundle['suite_snapshot']['cases'][0]['assertions'][0]
    record = next(a for a in bundle['artifacts'] if a['artifact_id'] == 'record-C01')
    return assertion, run, record


def value_bundle(actual, expected, operator='equals', pointer='', media='application/json'):
    bundle = effect_bundle()
    assertion, run, record = parts(bundle)
    assertion.update(kind='value', operator=operator, expected=expected, effect=None)
    record.update(content=actual, media_type=media)
    run['events'] = []
    run['observations'] = [{'assertion_id': 'a1', 'value': {'artifact_id': 'record-C01', 'pointer': pointer},
                            'effect_event_id': None}]
    return bundle


def citation(bundle, artifact_id, pointer, owner='baseline', container='bundle'):
    rows = bundle['artifacts'] if container == 'bundle' else bundle['suite_snapshot']['artifacts']
    artifact = next(a for a in rows if a['artifact_id'] == artifact_id)
    # Hash independently from content, not a digest computed by evaluator/Contract.
    content_hash = digest(artifact['content'].encode()) if artifact['media_type'] == 'text/plain' else H(artifact['content'])
    return {'owner': owner, 'container': container,
            'ref': {'artifact_id': artifact_id, 'pointer': pointer}, 'artifact_hash': content_hash}


def outcome(status, reason, citations=(), assertion_id='a1'):
    return {'assertion_id': assertion_id, 'status': status, 'reason': reason, 'citations': list(citations)}


def side(outcomes, status, run_id='B-C01', run_status='complete'):
    return {'presence': 'present', 'run_id': run_id, 'run_status': run_status,
            'status': status, 'outcomes': outcomes}


