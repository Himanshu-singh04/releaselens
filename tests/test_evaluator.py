class EvaluatorTests(unittest.TestCase):
    def validated(self, bundle, owner='baseline', raw=None):
        raw = canonical(seal(bundle)) if raw is None else raw
        self.assertLess(len(raw), 100000)
        imported = c.load(raw, owner)
        self.assertNotIn('diagnostic', imported)
        return imported['document']

    def check(self, bundle, expected, owner='baseline', run_id='B-C01'):
        normalized = self.validated(bundle, owner)
        before = copy.deepcopy(normalized)
        actual = e.evaluate_run(normalized, run_id, owner)
        self.assertEqual(actual, expected)
        self.assertEqual(normalized, before)
        return actual

    def effect_expected(self, bundle, status='pass', reason='MATCH', prefix='',
                        pointers=('/order_id', '/refund_state'), owner='baseline'):
        refs = [] if status == 'unknown' else [citation(bundle, 'record-C01', prefix + p, owner) for p in pointers]
        return side([outcome(status, reason, refs)], status)

    def test_fixed_paper_status_reason_and_exact_citation_tables(self):
        # B1 paper rows, NOT generated snapshots. C07 missing/C08 alignment await B4.
        expected = {
            'baseline': [('pass', 'MATCH'), ('pass', 'MATCH'), ('fail', 'MISMATCH'),
                         ('pass', 'MATCH'), ('pass', 'MATCH'), ('pass', 'MATCH'),
                         ('pass', 'MATCH'), ('pass', 'MATCH')],
            'candidate': [('pass', 'MATCH'), ('fail', 'MISMATCH'), ('pass', 'MATCH'),
                          ('unknown', 'MISSING_EVIDENCE'), ('unknown', 'INELIGIBLE_EFFECT'),
                          ('unknown', 'INELIGIBLE_EFFECT')],
        }
        for owner, rows in expected.items():
            original = fixture(owner)
            normalized = self.validated(copy.deepcopy(original), owner)
            self.assertEqual(normalized, original)  # Fixed fixtures require no repair.
            for n, (status, reason) in enumerate(rows, 1):
                with self.subTest(owner=owner, case=n):
                    cid = f'C{n:02}'
                    if status == 'unknown':
                        refs = []
                    elif n in (4, 8):
                        refs = [citation(original, 'reply-' + cid, None, owner)]
                    else:
                        refs = [citation(original, 'record-' + cid, p, owner)
                                for p in ('/order_id', '/ticket_state' if n == 3 else '/refund_state')]
                    run_id = ('B-' if owner == 'baseline' else 'C-') + cid
                    self.assertEqual(e.evaluate_run(normalized, run_id, owner),
                                     side([outcome(status, reason, refs)], status, run_id))

    def test_value_operators_are_literal_case_sensitive_and_do_not_trim(self):
        vectors = [('equals', 'yes', 'yes', True), ('equals', 'no', 'yes', False),
                   ('contains', 'Refund completed', 'fund', True),
                   ('contains', 'Refund completed', 'refund', False),
                   ('not_contains', 'pending', 'refunded', True),
                   ('not_contains', 'was refunded', 'refunded', False),
                   ('equals', ' yes ', 'yes', False), ('contains', 'yes', ' yes', False),
                   ('contains', 'a.*b', '.*', True), ('contains', 'axxb', '.*', False),
                   ('contains', '', '', True), ('not_contains', '', '', False)]
        for operator, actual, expected, match in vectors:
            with self.subTest(operator=operator, actual=actual, expected=expected):
                bundle = value_bundle(actual, expected, operator, None, 'text/plain')
                status, reason = ('pass', 'MATCH') if match else ('fail', 'MISMATCH')
                self.check(bundle, side([outcome(status, reason, [citation(bundle, 'record-C01', None)])], status))

