            assertions, observations, expected = [], [], []
            # Input a2,a10; output a10,a2. Each expected outcome is retained.
            for identifier, status in zip(('a2', 'a10'), statuses):
                a = dict(assertion, assertion_id=identifier, expected='different' if status == 'fail' else 'actual')
                assertions.append(a)
                observation = copy.deepcopy(run['observations'][0])
