    def test_internal_misuse_empty_malformed_and_faults_never_partial_success(self):
        normalized = self.validated(effect_bundle())
        for owner, run_id in [('suite', 'B-C01'), ('baseline', 'missing'), (None, 'B-C01')]:
            self.assertEqual(e.evaluate_run(normalized, run_id, owner), INTERNAL)
        for mode in ('empty', 'missing-kind', 'bad-kind', 'bad-operator', 'duplicate-assertion',
                     'hash-mismatch', 'duplicate-run', 'bad-status'):
            malformed = copy.deepcopy(normalized)
            assertions = malformed['suite_snapshot']['cases'][0]['assertions']
            if mode == 'empty':
                assertions.clear()
            elif mode == 'missing-kind':
                assertions[0].pop('kind')
            elif mode == 'bad-kind':
                assertions[0]['kind'] = 'invalid'
            elif mode == 'bad-operator':
                assertions[0]['operator'] = 'invalid'
            elif mode == 'duplicate-assertion':
                assertions.append(copy.deepcopy(assertions[0]))
            elif mode == 'hash-mismatch':
                malformed['runs'][0]['case_hash'] = 'sha256:' + '0' * 64
            elif mode == 'duplicate-run':
                malformed['runs'].append(copy.deepcopy(malformed['runs'][0]))
            else:
                malformed['runs'][0]['status'] = 'invalid'
            self.assertEqual(e.evaluate_run(malformed, 'B-C01', 'baseline'), INTERNAL, mode)
        for owner in ('baseline', 'candidate'):
            with patch.object(e, '_effect', side_effect=RuntimeError('CANARY_/private/evidence')):
                actual = e.evaluate_run(normalized, 'B-C01', owner)
            self.assertEqual(actual, INTERNAL)
            self.assertNotIn('CANARY', json.dumps(actual))
        # A failure after an earlier successful outcome must discard that outcome.
        bundle = effect_bundle()
        assertion, run, _ = parts(bundle)
        bundle['suite_snapshot']['cases'][0]['assertions'].append(dict(assertion, assertion_id='a2'))
        run['observations'].append(dict(run['observations'][0], assertion_id='a2'))
        normalized = self.validated(bundle)
        original = e._effect
        def fail_second(assertion, *args):
            if assertion['assertion_id'] == 'a2':
                raise RuntimeError('CANARY_/private/evidence')
            return original(assertion, *args)
        with patch.object(e, '_effect', side_effect=fail_second):
            self.assertEqual(e.evaluate_run(normalized, 'B-C01', 'baseline'), INTERNAL)


