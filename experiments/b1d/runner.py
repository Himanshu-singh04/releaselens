def require(condition, message):
    if not condition:
        raise RuntimeError(message)


def sha(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def write(path, data):
    with path.open('x') as stream:
        json.dump(data, stream, indent=2, ensure_ascii=True)
        stream.write('\n')


def git(*args):
    return subprocess.check_output(['/usr/bin/git', '-C', str(ROOT), *args], timeout=10)


def preserved():
    tracked29 = {ROOT / 'docs/decisions/009-standalone-archive-inspection.md',
                 ROOT / 'experiments/b1c/inspect_archive.py'}
    counts = {}
    for name, expected in MANIFESTS.items():
        manifest = ROOT / 'artifacts' / name / 'evidence-manifest.json'
        require(sha(manifest) == expected, 'Preserved manifest changed')
        entries = json.loads(manifest.read_text())['entries']
        for entry in entries:
            path = Path(entry['path'])
            if name == 'b1c' and path in tracked29:
                data = git('show', HEAD29 + ':' + str(path.relative_to(ROOT)))
                require(hashlib.sha256(data).hexdigest() == entry['sha256'], 'Preserved Git blob changed')
            elif 'sha256' in entry:
                require(sha(path) == entry['sha256'], 'Preserved disk entry changed')
            if 'link' in entry:
                require(os.readlink(path) == entry['link'], 'Preserved symlink changed')
        if name == 'b1c':
            expected_paths = {Path(e['path']) for e in entries if Path(e['path']).is_relative_to(BASE)}
            actual_paths = {p for p in BASE.rglob('*') if not p.is_dir() or p.is_symlink()}
            require(not BASE.is_symlink() and actual_paths == expected_paths, 'Extra or missing extracted-tree entry')
        counts[name] = len(entries)
    return counts


def allocation():
    return sum(p.lstat().st_blocks * 512 for base in (TASK, EVIDENCE)
               for p in [base, *base.rglob('*')])


def capacity():
    require(allocation() + RESERVE < BOUND, 'Task allocation limit')
    for path in (TASK, EVIDENCE):
        fs = os.statvfs(path)
        require(fs.f_bavail * fs.f_frsize >= RESERVE, 'Insufficient remaining space')


def environment():
    return {'PATH': os.defpath, 'HOME': str(TASK / 'home'),
            'TMPDIR': str(TASK / 'tmp'), 'TEMP': str(TASK / 'tmp'), 'TMP': str(TASK / 'tmp'),
            'XDG_CONFIG_HOME': str(TASK / 'config'), 'XDG_CACHE_HOME': str(TASK / 'cache'),
            'PIP_CONFIG_FILE': os.devnull, 'PIP_DISABLE_PIP_VERSION_CHECK': '1',
            'PYTHONDONTWRITEBYTECODE': '1', 'LC_ALL': 'C'}


def legacy_ids():
    return ([f'P{i:02}' for i in range(1, 49)] + [f'B{i:02}' for i in range(1, 27)]
            + ['RFC-sample', 'RFC-sample-product']
            + [f'bytes-{label}-{delta:+}' for label in ('artifact', 'suite', 'bundle') for delta in (-1, 0, 1)]
            + [f'depth-{label}-{depth}' for label in ('array', 'object') for depth in (31, 32, 33)]
            + ['utf8-byte-limit', 'utf8-byte-exact']
            + ['default-' + label for label in ('duplicate', 'NaN', 'surrogate', 'float', 'order', 'rounding')]
            + ['exact-type', 'semantic-hash', 'array-hash', 'unicode-hash',
               'diagnostic-ValueError', 'diagnostic-RuntimeError'])


def run(args, directory, label, deadline, legacy=False):
    """Bound both pipes while running; legacy record events delimit original named checks."""
    start = time.monotonic()
    last = start
    expiry = start + 30
    output = {'stdout': bytearray(), 'stderr': bytearray()}
    events = []
    pending = bytearray()
    reason = None
    termination = []
    process = subprocess.Popen([str(a) for a in args], cwd=TASK, env=environment(),
                               stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                               stderr=subprocess.PIPE, start_new_session=True)
    expected_ids = legacy_ids() if legacy else []
    try:
        with selectors.DefaultSelector() as selector:
            for name, pipe in [('stdout', process.stdout), ('stderr', process.stderr)]:
                os.set_blocking(pipe.fileno(), False)
                selector.register(pipe, selectors.EVENT_READ, name)
            while selector.get_map():
                now = time.monotonic()
                require(time.time() < deadline, 'Original execution-session clock exhausted')
                if now >= expiry:
                    reason = 'per-check-timeout'
                    break
                capacity()
                for key, _ in selector.select(min(0.2, expiry - now)):
                    chunk = os.read(key.fileobj.fileno(), 8192)
                    if not chunk:
                        selector.unregister(key.fileobj)
                        continue
                    name = key.data
                    remaining = STREAM_CAP - len(output[name])
                    output[name].extend(chunk[:remaining])
                    if len(chunk) > remaining:
                        reason = 'output-cap'
                        break
                    if legacy and name == 'stdout':
                        pending.extend(chunk)
                        while b'\n' in pending:
                            line, _, pending = pending.partition(b'\n')
                            event = json.loads(line)['legacy']
                            require(len(events) < 105 and event['id'] == expected_ids[len(events)], 'Legacy inventory/order changed')
                            stamp = time.monotonic()
                            require(stamp <= expiry, 'Legacy check timeout')
                            events.append({'record': event, 'elapsed_seconds': stamp - last,
                                           'exit_code': None, 'timeout': False})
                            last = stamp
                            expiry = stamp + 30
                            if not event['pass']:
                                reason = 'legacy-mismatch'
                                break
                    if reason:
                        break
                if reason:
                    break
            if not reason:
                try:
                    process.wait(timeout=max(0.001, min(30, expiry - time.monotonic(), deadline - time.time())))
                except subprocess.TimeoutExpired:
                    reason = 'process-exit-timeout'
    except Exception as error:
        reason = 'parent-' + type(error).__name__
    finally:
        # Reap whole process group on every exit, including descendants retaining pipe handles.
        for sig, wait in ((signal.SIGTERM, 0.5), (signal.SIGKILL, 1)):
            try:
                os.killpg(process.pid, sig)
                termination.append(signal.Signals(sig).name)
            except ProcessLookupError:
                pass
            try:
                process.wait(timeout=wait)
            except subprocess.TimeoutExpired:
                pass
        if process.poll() is None:
            reason = 'unreaped-child-STOP'
        process.stdout.close()
        process.stderr.close()
    elapsed = time.monotonic() - start
    for name, data in output.items():
        with (directory / (label + '.' + name)).open('xb') as stream:
            stream.write(data)
    for event in events:
        event['exit_code'] = process.returncode
        event['exit_scope'] = 'shared legacy process; per-row verdict retained independently'
    record = {'argv': [str(a) for a in args], 'environment': environment(), 'elapsed_seconds': elapsed,
              'check': label, 'active_legacy_check': (expected_ids[len(events)] if len(events) < 105 else 'report-finalization') if legacy else None,
              'active_interval_seconds': time.monotonic() - last,
              'exit_code': process.returncode, 'stop_reason': reason, 'termination': termination,
              'stdout_bytes': len(output['stdout']), 'stderr_bytes': len(output['stderr']),
              'legacy_events': events, 'timeout': bool(reason and 'timeout' in reason)}
    write(directory / (label + '.json'), record)
    require(reason is None and process.returncode == 0, 'Child failed; no retry')
    if legacy:
        require(len(events) == 105 and not pending, 'Incomplete legacy inventory')
        # The unmodified main also prints its original full report to stderr.
        report = json.loads(output['stderr'])
        require(report['total'] == 105 and report['passed'] == 105, 'Legacy report mismatch')
        require(report['cases'] == [e['record'] for e in events], 'Legacy observer changed a record')
        return report['cases']
    return bytes(output['stdout'])


def main():
    require(len(sys.argv) == 4, 'Expected phase, reviewed head and coordinator release record')
    phase, head, release_path = sys.argv[1:]
    require(phase in ('bootstrap', 'run1', 'run2'), 'Unknown phase')
    require(len(head) == 40 and git('rev-parse', 'HEAD').decode().strip() == head, 'Unreviewed HEAD')
    require(not git('status', '--porcelain'), 'Dirty checkout')
    release_path = Path(release_path).resolve()
    require(release_path.is_relative_to(EVIDENCE / 'continuation'), 'Release record outside task evidence')
    release = json.loads(release_path.read_text())
    require(release['head'] == head and release['issue'] == 30, 'Release revision mismatch')
    require(release['authorization'].startswith('https://github.com/Himanshu-singh04/releaselens/pull/31#issuecomment-'), 'Missing coordinator release locator')
    # This validates a supplied record, not the author's right to create it. Coordinator release is procedural.
    require(0 < release['remaining_worker_seconds'] <= 7200, 'Execution session budget')
    oracle = json.loads((ROOT / 'fixtures/b1d/oracle.json').read_text())
    for path, digest in oracle['sources'].items():
        require(sha(ROOT / path) == digest, 'Independent source changed')
    source_paths = [*sorted((ROOT / 'experiments/b1d').glob('*.py')),
                    *sorted((ROOT / 'fixtures/b1d').iterdir()), ROOT / 'docs/decisions/010-offline-runtime-validation.md']
    hashes = {str(p.relative_to(ROOT)): sha(p) for p in source_paths}
    require(hashes == release['files'], 'Exact reviewed packet hashes differ')
    before = preserved()
    capacity()
    require(not (OUTPUT / 'STOP.json').exists(), 'Prior failure; no automatic retry')
    if phase == 'bootstrap':
        require(not OUTPUT.exists() and not any(TASK.iterdir()), 'Unexpected task outputs')
        require(min(os.statvfs(p).f_bavail * os.statvfs(p).f_frsize for p in (TASK, EVIDENCE)) >= BOUND, 'Insufficient initial capacity')
        OUTPUT.mkdir()
        for part in ('home', 'tmp', 'config', 'cache'):
            (TASK / part).mkdir()
        deadline = time.time() + release['remaining_worker_seconds']
        write(OUTPUT / 'session.json', {'head': head, 'files': hashes, 'release_sha256': sha(release_path),
                                      'deadline_epoch': deadline, 'preservation_before': before})
    else:
        session = json.loads((OUTPUT / 'session.json').read_text())
        require(session['head'] == head and session['files'] == hashes and session['release_sha256'] == sha(release_path), 'Session binding changed')
        deadline = session['deadline_epoch']
        prerequisite = 'bootstrap' if phase == 'run1' else 'run1'
        require((OUTPUT / prerequisite / 'success.json').exists(), 'Prior phase not successful')
    require(time.time() < deadline, 'Execution deadline passed')
    directory = OUTPUT / phase
    directory.mkdir()  # existing start consumes this slot even after interruption; never retry
    write(directory / 'started.json', {'head': head, 'files': hashes, 'time_epoch': time.time()})
    try:
        if phase == 'bootstrap':
            commands = [
                [TARGET, '-I', '-B', BOOTSTRAP, 'base'],
                [TARGET, '-I', '-B', '-m', 'venv', '--without-pip', '--copies', VENV],
                [PYTHON, '-I', '-B', BOOTSTRAP, 'empty'],
                [PYTHON, '-I', '-B', BOOTSTRAP, 'install'],
                [PYTHON, '-I', '-B', BOOTSTRAP, 'installed'],
            ]
            for index, command in enumerate(commands):
                run(command, directory, f'prerequisite-{index + 1}', deadline)
            outcome = {'prerequisites': 5}
        else:
            run([PYTHON, '-I', '-B', BOOTSTRAP, 'installed'], directory, 'identity', deadline)
            retained = json.loads((ROOT / 'fixtures/b0b/vectors.json').read_text())
            identifiers = ['RFC-' + row[0] for row in retained['binary64']] + [c['id'] for c in oracle['checks']]
            require(len(identifiers) == len(set(identifiers)) == 96, 'New check inventory changed')
            results = []
            for identifier in identifiers:
                data = run([PYTHON, '-I', '-B', HARNESS, identifier], directory, identifier, deadline)
                row = json.loads(data)
                require(row['id'] == identifier and row['pass'] is True, 'Oracle mismatch')
                results.append(row)
            legacy = run([PYTHON, '-I', '-B', HARNESS, 'legacy'], directory, 'legacy', deadline, legacy=True)
            outcome = {'new': results, 'legacy': legacy}
            run([PYTHON, '-I', '-B', BOOTSTRAP, 'installed'], directory, 'identity-after', deadline)
            if phase == 'run2':
                previous = json.loads((OUTPUT / 'run1/success.json').read_text())
                require(previous['outcome'] == outcome, 'Confirmation differs; no third execution')
        after = preserved()
        require(time.time() < deadline, 'Execution-session deadline exhausted')
        require(not git('status', '--porcelain'), 'Unexpected checkout write')
        require({str(p.relative_to(ROOT)): sha(p) for p in source_paths} == hashes, 'Packet changed during execution')
        capacity()
        write(directory / 'success.json', {'head': head, 'files': hashes, 'outcome': outcome,
                                         'preservation_after': after, 'allocation_bytes': allocation()})
    except BaseException as error:
        if not (OUTPUT / 'STOP.json').exists():
            try:
                failure_preservation = {'entries': preserved(), 'allocation_bytes': allocation()}
            except Exception as integrity_error:
                failure_preservation = {'recheck_failed': type(integrity_error).__name__}
            write(OUTPUT / 'STOP.json', {'phase': phase, 'exception_class': type(error).__name__,
                                       'preservation_after_failure': failure_preservation,
                                       'action': 'STOP; retain partial evidence, no retry or oracle change'})
        raise


if __name__ == '__main__':
    main()
